describe('Local storage digit recognition', () => {
  it('separates bright low-chroma glyph strokes from the background', () => {
    const input = Uint8ClampedArray.from([
      200, 200, 200, 255, 119, 119, 119, 255, 190, 100, 100, 255, 160, 160, 160, 255,
    ]);

    expect([...binarizeQuantityPixels(input, 120)]).toEqual([
      0, 0, 0, 255, 255, 255, 255, 255, 255, 255, 255, 255, 0, 0, 0, 255,
    ]);
  });
  it('does not interpret a bright slot frame as the digit one', () => {
    const rgb = new Uint8Array(50 * 20 * 3);
    for (let y = 3; y < 16; y++)
      for (let x = 42; x < 44; x++) for (let c = 0; c < 3; c++) rgb[(y * 50 + x) * 3 + c] = 255;
    expect(readQuantityPixels(rgb, 50, 20, 3)).toBeNull();
  });
  for (const fixture of fixtures)
    it('reads ' + fixture.text + ' despite surrounding icon highlights', () => {
      const pixels = Uint8Array.from(fixture.rows.join(''), (v) => (v === '1' ? 255 : 0));
      const rgb = Uint8Array.from(
        { length: pixels.length * 3 },
        (_, i) => pixels[Math.floor(i / 3)],
      );
      expect(readQuantityPixels(rgb, 50, 20, 3)?.text).toBe(fixture.text);
    });
  it('does not invent a quantity in an empty slot', () => {
    expect(readQuantityPixels(new Uint8Array(50 * 20 * 4), 50, 20)).toBeNull();
  });
  it('rejects malformed input', () => {
    expect(readQuantityPixels(new Uint8Array(1), 50, 20)).toBeNull();
  });
});
